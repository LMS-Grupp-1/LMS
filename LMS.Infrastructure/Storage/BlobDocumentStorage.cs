using Azure;
using Azure.Storage.Blobs;
using Azure.Storage.Blobs.Models;
using Domain.Contracts;
using Domain.Models.Exceptions.DocumentExceptions;

namespace LMS.Infrastructure.Storage;

public sealed class BlobDocumentStorage : IDocumentStorage
{
    private readonly BlobContainerClient _container;

    public BlobDocumentStorage(BlobContainerClient container)
    {
        _container = container;
    }

    public async Task SaveAsync(
        string blobPath,
        Stream content,
        string contentType,
        CancellationToken cancellationToken)
    {
        var blob = GetBlobClient(blobPath);

        var options = new BlobUploadOptions
        {
            HttpHeaders = new BlobHttpHeaders
            {
                ContentType = contentType
            },
            Conditions = new BlobRequestConditions
            {
                IfNoneMatch = ETag.All
            }
        };

        await blob.UploadAsync(
            content,
            options,
            cancellationToken);
    }

    public async Task<Stream> OpenReadAsync(
        string blobPath,
        CancellationToken cancellationToken)
    {
        var blob = GetBlobClient(blobPath);

        try
        {
            return await blob.OpenReadAsync(
                cancellationToken: cancellationToken);
        }
        catch (RequestFailedException exception)
            when (exception.Status == 404)
        {
            throw new DocumentNotFoundException(
                "The document file could not be found.");
        }
    }

    public async Task DeleteAsync(
        string blobPath,
        CancellationToken cancellationToken)
    {
        var blob = GetBlobClient(blobPath);

        await blob.DeleteIfExistsAsync(
            cancellationToken: cancellationToken);
    }

    private BlobClient GetBlobClient(string blobPath)
    {
        // Accept only storage identifiers generated by the server.
        if (!Guid.TryParseExact(blobPath, "N", out _))
        {
            throw new ArgumentException(
                "The storage identifier must be a GUID without hyphens.",
                nameof(blobPath));
        }

        return _container.GetBlobClient(blobPath);
    }
}
